public class Variable {
    /**
     * @param args
     */
    public static void main(String[] args) {
        String name = "John";
        char grade = 'A';
        int age = 25;
        double salary = 50000.50;
        System.out.println("Name: " + name);
        System.out.println("Grade: " + grade);
        System.out.println("Age: " + age);
        System.out.println("Salary: " + salary);
    }
}